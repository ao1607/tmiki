"""Generate rust/crates/tmi-diffmerge/src/html_text.rs: the page template, CSS
and JavaScript of tmi/diff_html.py, which the Rust `diff --html` writes byte for
byte (RUST_MIGRATION.md 4a).

    python tools/gen_diff_html.py          # rewrite the file
    python tools/gen_diff_html.py --check  # exit 1 when it is out of date

Rerun after changing tmi/diff_html.py's _CSS, _JS or _PAGE_TEMPLATE.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
TARGET = ROOT / "rust" / "crates" / "tmi-diffmerge" / "src" / "html_text.rs"


def literal(text: str) -> str:
    hashes = "#"
    while f'"{hashes}' in text:
        hashes += "#"
    return f'r{hashes}"{text}"{hashes}'


def render() -> str:
    from tmi import diff_html

    parts = [
        "//! Generated by tools/gen_diff_html.py from tmi/diff_html.py; do not edit.\n",
        f"pub const CSS: &str = {literal(diff_html._CSS)};\n",
        f"pub const JS: &str = {literal(diff_html._JS)};\n",
        f"pub const PAGE: &str = {literal(diff_html._PAGE_TEMPLATE.template)};\n",
        f"pub const EMPTY_SECTION: &str = {literal(diff_html._EMPTY_SECTION)};\n",
    ]
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
    if args.check:
        if current != text:
            print(f"{TARGET} is out of date: run python tools/gen_diff_html.py")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
