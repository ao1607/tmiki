"""Write rust/crates/tmi-cli/src/casefold_table.rs: every code point whose
`str.casefold()` differs from itself, with its folding, as this Python
(its Unicode version) computes it. `tmiki log --author` casefolds the author
text (RUST_MIGRATION.md 3b-1).

    python tools/gen_casefold.py
"""
from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "rust" / "crates" / "tmi-cli" / "src" / "casefold_table.rs"


def main() -> int:
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        folded = ch.casefold()
        if folded != ch:
            rows.append((cp, folded))
    lines = [
        "//! Generated by tools/gen_casefold.py: `str.casefold()` of every code",
        f"//! point it changes (Python {sys.version_info.major}.{sys.version_info.minor}, "
        f"Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        f'pub const PYTHON_VERSION: &str = "{sys.version_info.major}.{sys.version_info.minor}";',
        "",
        "pub const CASEFOLD: &[(u32, &str)] = &[",
    ]
    for cp, folded in rows:
        text = "".join(f"\\u{{{ord(c):x}}}" for c in folded)
        lines.append(f'    (0x{cp:x}, "{text}"),')
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(rows)} code points)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
