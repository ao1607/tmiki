"""Write rust/crates/tmi-cli/src/help_text.rs: argparse's `-h` text of every
tmi parser (tmi.cli.build_parser), as Python formats it for an 80-column
output (COLUMNS=80, or a stdout that is not a terminal).

    python tools/gen_cli_help.py          # rewrite the file
    python tools/gen_cli_help.py --check  # exit 1 if it is out of date

The Rust front door prints these for `tmiki -h`, `tmi <command> -h` and
`tmi <command> <subcommand> -h` when the Python it would hand the command
to is the version recorded here (argparse's layout changes between
versions); otherwise it hands `-h` to Python (RUST_MIGRATION.md 3b-1).
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "rust" / "crates" / "tmi-cli" / "src" / "help_text.rs"


def collect() -> list[tuple[tuple[str, ...], str]]:
    os.environ["COLUMNS"] = "80"
    sys.path.insert(0, str(ROOT))
    from tmi.cli import build_parser

    rows: list[tuple[tuple[str, ...], str]] = []

    def walk(parser: argparse.ArgumentParser, path: tuple[str, ...]) -> None:
        rows.append((path, parser.format_help()))
        for action in parser._actions:
            if isinstance(action, argparse._SubParsersAction):
                for name, sub in action.choices.items():
                    walk(sub, path + (name,))

    walk(build_parser(), ())
    return rows


def rust_str(text: str) -> str:
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 0x20:
            out.append(f"\\u{{{ord(ch):x}}}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def render() -> str:
    version = f"{sys.version_info.major}.{sys.version_info.minor}"
    lines = [
        "//! Generated by tools/gen_cli_help.py: argparse's help of every tmi",
        "//! parser at 80 columns. Do not edit.",
        "",
        f'pub const PYTHON_VERSION: &str = "{version}";',
        "",
        "pub const HELP: &[(&[&str], &str)] = &[",
    ]
    for path, text in collect():
        keys = ", ".join(rust_str(p) for p in path)
        lines.append(f"    (&[{keys}], {rust_str(text)}),")
    lines.append("];")
    return "\n".join(lines) + "\n"


OUT_PARSERS = ROOT / "rust" / "crates" / "tmi-cli" / "src" / "argparse_table.rs"


def _action_name(action: argparse.Action) -> str | None:
    return argparse._get_action_name(action)


def render_parsers() -> str:
    """Every parser without subparsers (the ones a command line ends in):
    its prog, usage and actions, for the front door's argparse errors
    (RUST_MIGRATION.md 4b, argparse_errors.rs)."""
    os.environ["COLUMNS"] = "80"
    sys.path.insert(0, str(ROOT))
    from tmi.cli import build_parser

    def nargs_code(a: argparse.Action) -> str:
        if a.nargs is None:
            return "1"
        if a.nargs in (0, "?", "*", "+"):
            return str(a.nargs)
        raise SystemExit(f"nargs {a.nargs!r} of {a.option_strings or a.dest} is not handled")

    def empty_ok(parser: argparse.ArgumentParser, a: argparse.Action) -> bool:
        # _get_values(action, []) for nargs '?' and '*' raises nothing
        try:
            parser._get_values(a, [])
            return True
        except argparse.ArgumentError:
            return False

    rows = []

    def walk(parser: argparse.ArgumentParser, path: tuple[str, ...]) -> None:
        subs = [a for a in parser._actions if isinstance(a, argparse._SubParsersAction)]
        for action in subs:
            for name, sub in action.choices.items():
                walk(sub, path + (name,))
        if subs or not path:
            return
        acts = []
        index = {a: i for i, a in enumerate(parser._actions)}
        for a in parser._actions:
            kind = type(a).__name__
            if kind not in ("_HelpAction", "_StoreAction", "_StoreTrueAction", "_StoreFalseAction",
                            "_StoreConstAction", "_CountAction"):
                raise SystemExit(f"action {kind} in {path} is not handled")
            if a.type not in (None, int, str, Path):
                raise SystemExit(f"type {a.type} in {path} is not handled")
            groups = [g for g in parser._mutually_exclusive_groups if a in g._group_actions]
            conflicts = sorted(index[b] for g in groups for b in g._group_actions if b is not a)
            if any(g.required for g in groups):
                raise SystemExit(f"required group in {path} is not handled")
            choices = None if a.choices is None else [str(c) for c in a.choices]
            acts.append(
                "PAct { "
                f"opts: &[{', '.join(rust_str(s) for s in a.option_strings)}], "
                f"nargs: {rust_str(nargs_code(a))}, "
                f"choices: {'None' if choices is None else 'Some(&[' + ', '.join(rust_str(c) for c in choices) + '])'}, "
                f"int: {'true' if a.type is int else 'false'}, "
                f"required: {'true' if a.required else 'false'}, "
                f"name: {rust_str(_action_name(a) or '')}, "
                f"help: {'true' if kind == '_HelpAction' else 'false'}, "
                f"empty_ok: {'true' if a.nargs not in ('?', '*') or empty_ok(parser, a) else 'false'}, "
                f"conflicts: &[{', '.join(str(c) for c in conflicts)}] "
                "}"
            )
        rows.append(
            f"    PParser {{ path: &[{', '.join(rust_str(p) for p in path)}], prog: {rust_str(parser.prog)}, "
            f"usage: {rust_str(parser.format_usage())}, actions: &[\n        "
            + ",\n        ".join(acts)
            + ",\n    ] },"
        )

    top = build_parser()
    walk(top, ())
    version = f"{sys.version_info.major}.{sys.version_info.minor}"
    lines = [
        "//! Generated by tools/gen_cli_help.py: every tmi parser a command line",
        "//! ends in, with its actions, as argparse sees them. Do not edit.",
        "",
        f'pub const PYTHON_VERSION: &str = "{version}";',
        f"pub const TOP_USAGE: &str = {rust_str(top.format_usage())};",
        "/// The top parser's subcommands (`choices` of its subparsers action), and",
        "/// those of the parsers with subparsers of their own.",
        "pub const TOP_CHOICES: &[&str] = &["
        + ", ".join(rust_str(c) for a in top._actions if isinstance(a, argparse._SubParsersAction) for c in a.choices)
        + "];",
        "pub const NESTED: &[(&str, &[&str])] = &["
        + ", ".join(
            f"({rust_str(name)}, &[{', '.join(rust_str(c) for c in s.choices)}])"
            for a in top._actions if isinstance(a, argparse._SubParsersAction)
            for name, sub in a.choices.items()
            for s in sub._actions if isinstance(s, argparse._SubParsersAction)
        )
        + "];",
        "",
        "pub struct PAct {",
        "    pub opts: &'static [&'static str],",
        "    /// \"0\", \"1\" (nargs None), \"?\", \"*\" or \"+\"",
        "    pub nargs: &'static str,",
        "    pub choices: Option<&'static [&'static str]>,",
        "    pub int: bool,",
        "    pub required: bool,",
        "    /// `_get_action_name(action)`",
        "    pub name: &'static str,",
        "    pub help: bool,",
        "    /// `_get_values(action, [])` raises nothing (nargs \"?\" / \"*\")",
        "    pub empty_ok: bool,",
        "    /// indices of the actions a mutually exclusive group forbids with it",
        "    pub conflicts: &'static [usize],",
        "}",
        "",
        "pub struct PParser {",
        "    pub path: &'static [&'static str],",
        "    pub prog: &'static str,",
        "    pub usage: &'static str,",
        "    pub actions: &'static [PAct],",
        "}",
        "",
        "pub const PARSERS: &[PParser] = &[",
        *rows,
        "];",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = [(OUT, render()), (OUT_PARSERS, render_parsers())]
    if args.check:
        stale = [str(path) for path, text in outputs
                 if (path.read_text(encoding="utf-8") if path.exists() else "") != text]
        if stale:
            print(f"{', '.join(stale)} out of date: python tools/gen_cli_help.py")
            return 1
        print("help text and parser tables up to date")
        return 0
    for path, text in outputs:
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
